"""Verification pass: checks that the generated answer is grounded in the context."""

from __future__ import annotations

import structlog

from app.db.models import VerificationVerdict
from app.services.llm import LLMProvider

log = structlog.get_logger(__name__)

_VERIFY_SYSTEM = """You are a factual verification assistant.
You will be given:
1. A list of context chunks retrieved from a document.
2. An answer generated by an AI assistant.

Your task: determine whether every factual claim in the answer is directly supported by
the provided context chunks.

Respond with EXACTLY one of these three words (no other text):
- supported
- partially
- unsupported"""


async def verify_answer(
    answer: str,
    context_chunks: list[str],
    llm: LLMProvider,
) -> VerificationVerdict:
    """Run a verification pass and return the verdict."""
    numbered = "\n".join(f"[{i+1}] {c}" for i, c in enumerate(context_chunks))
    prompt = f"Context chunks:\n{numbered}\n\nAnswer to verify:\n{answer}"

    raw = await llm.complete(
        system=_VERIFY_SYSTEM,
        messages=[{"role": "user", "content": prompt}],
        temperature=0.0,
    )
    raw = raw.strip().lower()

    try:
        verdict = VerificationVerdict(raw)
    except ValueError:
        log.warning("Unexpected verification verdict", raw=raw)
        verdict = VerificationVerdict.partially

    log.info("Verification verdict", verdict=verdict.value)
    return verdict
